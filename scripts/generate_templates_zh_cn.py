def build_templates(locale: str = "zh-CN") -> dict:
    locales: dict[str, dict[str, dict[str, list[dict]]]] = {locale: {}}
    for persona, types in TEMPLATE_TEXTS.items():
        locales[locale][persona] = {}
        for filler_type, texts in types.items():
            if len(texts) < MIN_COUNT:
                raise ValueError(
                    f"{persona}/{filler_type} has {len(texts)} texts, need >= {MIN_COUNT}"
                )
            seen_texts: set[str] = set()
            items: list[dict] = []
            for index, text in enumerate(texts[:MIN_COUNT], start=1):
                if text in seen_texts:
                    raise ValueError(f"duplicate text in {persona}/{filler_type}: {text}")
                seen_texts.add(text)
                if not BOUNDARY_RE.search(text):
                    raise ValueError(f"missing boundary in {persona}/{filler_type}: {text}")
                if len(text) > MAX_LEN:
                    raise ValueError(
                        f"text too long ({len(text)}>{MAX_LEN}) in {persona}/{filler_type}: {text}"
                    )
                items.append(
                    {
                        "template_id": f"{locale}.{persona}.{filler_type.lower()}.{index:03d}",
                        "text": text,
                        "enabled": True,
                        "weight": 1,
                    }
                )
            locales[locale][persona][filler_type] = items
    return locales


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    output = root / "configs" / "templates.zh-CN.v1.json"
    payload = {
        "version": "templates-v1",
        "default_persona": "male_white_collar",
        "locales": build_templates(),
    }
    output.write_text(
        json.dumps(payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    total = sum(
        len(templates)
        for personas in payload["locales"].values()
        for types in personas.values()
        for templates in types.values()
    )
    print(f"wrote {total} templates to {output}")


if __name__ == "__main__":
    main()
